function render() {
  const app = document.getElementById("app");
  app.replaceChildren(
    h("div", { class: "page-head" }, h("div", {}, h("h1", {}, "使用指南"), h("p", {}, "按“我想做什么”来找；每一步都能直接点进去。"))),
    h("div", { class: "guide" },
      h("nav", { class: "toc card" }, ...G.map(([id, t]) => h("a", { href: "#" + id }, t)), h("a", { href: "#faq" }, "❓ 常见问题")),
      h("div", { class: "grid", style: { gap: "14px" } },
        ...G.map(([id, t, d, steps]) => h("div", { class: "card", id }, h("h3", {}, t), d ? h("div", { class: "sub" }, d) : null,
          h("ol", { class: "steps" }, ...steps.map((s) => h("li", {}, ...s))))),
        h("div", { class: "card", id: "faq" }, h("h3", {}, "❓ 常见问题"), ...FAQ.map(([q, a]) => h("div", {}, h("div", { class: "q" }, q), h("div", { class: "small" }, a)))))));
}
(async () => { await UI.nav("guide", { picker: false }); render(); })();
